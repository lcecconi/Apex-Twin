class IconRenderer:
    @staticmethod
    def draw_xbm(p: QPainter, x: int, y: int, xbm_bytes: bytes, fg: QColor, w: int = 16, h: int = 16):
        """Draw 1-bit monochrome XBM bitmap bit-by-bit."""
        bytes_per_row = (w + 7) // 8
        p.save()
        p.setPen(Qt.NoPen)
        p.setBrush(fg)
        for row in range(h):
            for col_byte in range(bytes_per_row):
                byte_val = xbm_bytes[row * bytes_per_row + col_byte]
                for bit in range(8):
                    px = col_byte * 8 + bit
                    if px < w and (byte_val & (1 << bit)):
                        p.drawRect(x + px, y + row, 1, 1)
        p.restore()

    @staticmethod
    def draw_battery(p: QPainter, x: int, y: int, voltage: float, percent: int, fg: QColor):
        """Draw dynamic battery outline with positive terminal nipple and fill bars."""
        p.save()
        p.setPen(fg)
        p.drawRect(x, y, 20, 11)
        p.fillRect(x + 20, y + 3, 2, 5, fg)

        fill_w = int((percent * 16) / 100)
        fill_w = max(0, min(16, fill_w))
        if fill_w > 0:
            p.fillRect(x + 2, y + 2, fill_w, 7, fg)
        p.restore()

    @staticmethod
    def draw_signal_bars(p: QPainter, x: int, y: int, rssi: int, connected: bool, fg: QColor):
        """Draw 4-bar RF signal strength indicator or disconnected 'X'."""
        p.save()
        p.setPen(fg)
        if not connected:
            p.drawLine(x, y + 2, x + 12, y + 12)
            p.drawLine(x + 12, y + 2, x, y + 12)
            p.restore()
            return

        bars = 4 if rssi > -60 else (3 if rssi > -72 else (2 if rssi > -82 else 1))
        for i in range(4):
            bar_h = (i + 1) * 3
            bx = x + (i * 4)
            by = y + 12 - bar_h
            if i < bars:
                p.fillRect(bx, by, 3, bar_h, fg)
            else:
                p.drawRect(bx, by, 3, bar_h)
        p.restore()

    @staticmethod
    def draw_alarm_badge(p: QPainter, x: int, y: int, w: int, h: int, xbm_bytes: bytes, text: str, invert: bool, bg: QColor, fg: QColor):
        """Draw high-contrast alarm badge with icon."""
        p.save()
        if invert:
            p.fillRect(x, y, w, h, fg)
            if xbm_bytes:
                IconRenderer.draw_xbm(p, x + 3, y + (h - 16) // 2, xbm_bytes, bg)
            p.setPen(bg)
            p.setFont(QFont("SansSerif", 9, QFont.Bold))
            p.drawText(QRectF(x + 20, y, w - 20, h), Qt.AlignVCenter | Qt.AlignLeft, text)
        else:
            p.setPen(fg)
            p.drawRoundedRect(x, y, w, h, 3, 3)
            if xbm_bytes:
                IconRenderer.draw_xbm(p, x + 3, y + (h - 16) // 2, xbm_bytes, fg)
            p.setFont(QFont("SansSerif", 9, QFont.Bold))
            p.drawText(QRectF(x + 20, y, w - 20, h), Qt.AlignVCenter | Qt.AlignLeft, text)
        p.restore()
